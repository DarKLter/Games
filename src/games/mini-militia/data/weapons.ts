const WEAPON_MAP = new Map<string, MmWeaponDef>(MM_WEAPONS.map((w) => [w.id, w]));

export function getMmWeaponById(id: string): MmWeaponDef {
  return WEAPON_MAP.get(id) ?? MM_WEAPONS[3]; // default Magnum
}

export function canDualWieldPair(weaponAId: string, weaponBId: string): boolean {
  const a = getMmWeaponById(weaponAId);
  const b = getMmWeaponById(weaponBId);
  if (!a.oneHanded || !b.oneHanded) return false;
  // Cannot dual-wield two Riot Shields simultaneously
  if (a.isShield && b.isShield) return false;
  return true;
}

