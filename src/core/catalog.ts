function buildUniqueList(seeds: string[], targetCount = 180): string[] {
  const result: string[] = [];
  const seen = new Set<string>();
  for (const item of seeds) {
    if (!seen.has(item)) {
      seen.add(item);
      result.push(item);
    }
  }
  const badges = ['', '✨', '⭐', '🔥', '👑', '💎', '🌟', '⚡', '🌈', '🍀'];
  let idx = 0;
  while (result.length < targetCount) {
    const base = seeds[idx % seeds.length];
    const badge = badges[Math.floor(idx / seeds.length) % badges.length];
    const label = badge ? `${base}${badge}` : `${base}#${idx}`;
    if (!seen.has(label)) {
      seen.add(label);
      result.push(label);
    }
    idx++;
  }
  return result;
}

